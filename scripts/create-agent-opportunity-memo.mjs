#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const TOPICS_DIR = path.join("sources", "agent-research", "topics");
const MEMOS_DIR = path.join("sources", "agent-research", "memos");

function slugify(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function readTopic(slug) {
  const filePath = path.join(TOPICS_DIR, `${slug}.md`);
  if (!fs.existsSync(filePath)) {
    throw new Error(`Topic not found: ${filePath}`);
  }
  return {
    filePath,
    content: fs.readFileSync(filePath, "utf8"),
  };
}

function section(content, heading) {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const pattern = new RegExp(`^##\\s+\\d+\\.\\s+${escaped}\\s*$([\\s\\S]*?)(?=^##\\s+\\d+\\.|(?![\\s\\S]))`, "im");
  const match = content.match(pattern);
  return match ? match[1].trim().replace(/\n---\s*$/g, "").trim() : "_Not specified in topic file._";
}

function extractInlineField(content, label, fallback = "Not specified") {
  const pattern = new RegExp(`\\*\\*${label}:\\*\\*\\s*([^\\n]+)`, "i");
  const match = content.match(pattern);
  return match ? match[1].trim().replace(/`/g, "") : fallback;
}

function buildMemo(slug, topic) {
  const title = extractInlineField(topic.content, "Topic ID", slug);
  const priority = extractInlineField(topic.content, "Priority", "P2");
  const recommendation = extractInlineField(topic.content, "Recommendation", "Defer");
  const today = new Date().toISOString().slice(0, 10);

  return `# Agent Opportunity Memo: ${title}

**Memo ID:** agent-opportunity-${slug}  
**Dato:** ${today}  
**Topic file:** \`${topic.filePath}\`  
**Priority:** ${priority}  
**Recommendation:** ${recommendation}  
**Generated by:** \`scripts/create-agent-opportunity-memo.mjs\`  
**Mode:** Research Agent v0.1 / read-only / suggest-only

---

## 1. External signal

${section(topic.content, "External signal")}

---

## 2. Sources

${section(topic.content, "External sources to inspect")}

---

## 3. Pattern

${section(topic.content, "Research question")}

---

## 4. PILAR problem mapping

${section(topic.content, "PILAR problem mapping")}

---

## 5. Proposed agent

${section(topic.content, "Proposed agent")}

---

## 6. MVP scope

${section(topic.content, "MVP scope")}

---

## 7. Data to log

${section(topic.content, "Data to log later")}

---

## 8. Eval criteria

${section(topic.content, "Eval criteria")}

---

## 9. Risks

| Risk | Severity | Mitigation |
|---|---:|---|
| Browser or UI automation becomes flaky | Medium | Start with checklist/dry-run before full browser automation. |
| Agent marks output as safe without enough evidence | High | Keep Research Agent suggest-only and require human approval. |
| Testing focuses on labels but misses engineering errors | High | Combine deterministic checks with Eval Agent and manual review. |
| Old database output is mistaken for new prompt behavior | Medium | Require new runs for prompt/report changes. |

---

## 10. Sprint suggestion

${section(topic.content, "Recommended next sprint")}

---

## 11. Final recommendation

Build the proposed workflow incrementally. Keep v0.1 read-only/suggest-only, use deterministic checks first, and require human approval before any runtime agent receives write access.
`;
}

function main() {
  const rawSlug = process.argv[2];
  if (!rawSlug) {
    console.error("Usage: node scripts/create-agent-opportunity-memo.mjs <topic-slug>");
    console.error("Example: node scripts/create-agent-opportunity-memo.mjs ai-agent-testing");
    process.exit(1);
  }

  const slug = slugify(rawSlug);
  const topic = readTopic(slug);
  const memo = buildMemo(slug, topic);

  fs.mkdirSync(MEMOS_DIR, { recursive: true });
  const outPath = path.join(MEMOS_DIR, `agent-opportunity-${slug}.md`);
  fs.writeFileSync(outPath, memo, "utf8");

  console.log(`OK wrote ${outPath}`);
}

try {
  main();
} catch (error) {
  console.error(`FAILED ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
