function patchCalculationPage(text) {
  text = addImport(text, 'import type { PilarDisplayLanguage } from "@/lib/international/display";');
  text = text.replace(
    /const LABELS: Record<Locale, Record<string, string>> = \{/,
    'const LABELS: Record<PilarDisplayLanguage, Record<string, string>> = {'
  );
  text = addEnBlockToCalculationPage(text);
  text = addLabelToBlock(text, "nb", "step", "Steg");
  text = addLabelToBlock(text, "nb", "control", "Kontroll");
  text = addLabelToBlock(text, "nn", "step", "Steg");
  text = addLabelToBlock(text, "nn", "control", "Kontroll");
  text = addLabelToBlock(text, "en", "step", "Step");
  text = addLabelToBlock(text, "en", "control", "Check");

  // Ensure the label set is selected from the calculation sheet display language once the sheet exists.
  text = text.replace(
    /  const L = LABELS\[locale\];\n/,
    '  const initialLabels = LABELS[locale];\n'
  );
  text = text.replace(/\{L\.loadingError\}/g, "{initialLabels.loadingError}");
  text = text.replace(/\{L\.back\}/g, "{initialLabels.back}");

  if (!text.includes("const displayLanguage = (sheet.meta.displayLanguage ?? locale) as PilarDisplayLanguage;")) {
    text = text.replace(
      /  return \(\n    <main className="beregning-page">/,
      '  const displayLanguage = (sheet.meta.displayLanguage ?? locale) as PilarDisplayLanguage;\n  const L = LABELS[displayLanguage] ?? LABELS[locale];\n\n  return (\n    <main className="beregning-page">'
    );
  }

  // Kill the source of UNDEFINED 01 in exported PDFs.
  text = text.replace(
    /step\.isControlStep \? "Kontroll" : `Steg \$\{String\(step\.number\)\.padStart\(2, "0"\)\}`/g,
    'step.isControlStep ? (L.control ?? "Check") : `${L.step ?? "Step"} ${String(step.number).padStart(2, "0")}`'
  );
  text = text.replace(
    /step\.isControlStep \? \(L\.control \?\? "Check"\) : `\$\{L\.step \?\? "Step"\} \$\{String\(step\.number\)\.padStart\(2, "0"\)\}`/g,
    'step.isControlStep ? (L.control ?? "Check") : `${L.step ?? "Step"} ${String(step.number).padStart(2, "0")}`'
  );
  text = text.replace(/\$\{L\.step\} \$\{String\(step\.number\)\.padStart\(2, "0"\)\}/g, '${L.step ?? "Step"} ${String(step.number).padStart(2, "0")}');
  text = text.replace(/\bUNDEFINED\b/g, "Step");

  return text;
}

