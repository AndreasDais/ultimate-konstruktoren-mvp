import fs from "node:fs";
import path from "node:path";

function exists(file) {
  return fs.existsSync(file);
}

function read(file) {
  return fs.readFileSync(file, "utf8");
}

function write(file, text) {
  fs.writeFileSync(file, text, "utf8");
}

function patchFile(file, patcher) {
  if (!exists(file)) {
    console.log(`SKIP ${file} (not found)`);
    return;
  }
  const before = read(file);
  const after = patcher(before);
  if (after !== before) {
    write(file, after);
    console.log(`PATCHED ${file}`);
  } else {
    console.log(`OK ${file}`);
  }
}

function addImport(text, importLine) {
  if (text.includes(importLine)) return text;
  const importMatches = [...text.matchAll(/^import .*?;\n/gm)];
  if (importMatches.length === 0) return `${importLine}\n${text}`;
  const insertAt = importMatches[importMatches.length - 1].index + importMatches[importMatches.length - 1][0].length;
  return `${text.slice(0, insertAt)}${importLine}\n${text.slice(insertAt)}`;
}

function addLabelToBlock(text, blockName, key, value) {
  const re = new RegExp(`(${blockName}:\\s*\\{[\\s\\S]*?)(\\n\\s*\\},)`, "m");
  return text.replace(re, (match, body, close) => {
    if (new RegExp(`\\n\\s*${key}:`).test(body)) return match;
    return `${body}\n    ${key}: ${JSON.stringify(value)},${close}`;
  });
}

