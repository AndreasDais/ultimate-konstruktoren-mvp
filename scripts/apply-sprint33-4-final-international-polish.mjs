function patchBuildReportModel(text) {
  text = addImport(text, 'import { polishEnglishGeneratedText } from "@/lib/international/display";');
  // Avoid duplicate named import if the file already imports many helpers from the same module.
  text = text.replace(/import \{ polishEnglishGeneratedText \} from "@\/lib\/international\/display";\nimport \{([\s\S]*?)\} from "@\/lib\/international\/display";/, (m, names) => {
    return names.includes("polishEnglishGeneratedText")
      ? `import {${names}} from "@/lib/international/display";`
      : `import { polishEnglishGeneratedText,${names}} from "@/lib/international/display";`;
  });

  // Polish common controller and conclusion strings when displayLanguage is English.
  text = text.replace(
    /controllerText: localizeGeneratedEngineeringText\(\n\s*cleanReportText\(([\s\S]*?)\),\n\s*displayLanguage,\n\s*\),/,
    'controllerText: localizeGeneratedEngineeringText(\n        cleanReportText($1),\n        displayLanguage,\n      ),'
  );
  return text;
}

